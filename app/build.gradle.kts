// Release signing: CI passes these as environment variables (from GitHub secrets);
// locally they come from keystore.properties, which is git-ignored.
val keystoreProps = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}
fun signingValue(env: String, prop: String): String? =
    System.getenv(env)?.takeIf { it.isNotBlank() } ?: keystoreProps.getProperty(prop)

val releaseStoreFile = signingValue("MIDAS_KEYSTORE_FILE", "storeFile")

